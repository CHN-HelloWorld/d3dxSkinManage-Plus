KEY_CODES = {name: code for code, names in _NAMES_BY_CODE.items() for name in names}


def key_identity(token: str) -> int | str:
    """返回虚拟键码；非键盘词项保留原有身份。"""
    key = token.lower()
    if len(key) == 1 and key.isascii() and key.isalnum():
        return ord(key.upper())
    if key.startswith("0x"):
        try:
            return int(key, 16)
        except ValueError:
            return key
    return KEY_CODES.get(key.removeprefix("vk_"), key)
